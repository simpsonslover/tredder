"""
Fusion script: build the tredder rev A simulation model and save it as a Fusion file (.f3d).

Run it in Fusion: UTILITIES > ADD-INS > Scripts and Add-Ins > "+" (Script or add-in from
device) > pick this folder > Run. It:
  1. imports tredder-revA-sim.step (in this folder) into a new design,
  2. names every body ("RP2350 - heat 0.10 W", ...) and gives it its material
     (Fusion library materials, plus custom FR4 / mold compound / LiPo / foam with
     the values from FUSION_SIM.md),
  3. saves tredder-revA-sim.f3d next to this script.

Generated by hardware/tools/export_mech.py together with bodies.json; edit them there.
Fusion's API cannot create simulation studies or loads: add the heat loads and
constraints in the Simulation workspace (the body names say how much heat each one makes).
"""
import json
import os
import traceback

import adsk.core
import adsk.fusion

HERE = os.path.dirname(os.path.abspath(__file__))
TOL_MM = 0.05


def find_material(app, names):
    for name in names:
        for i in range(app.materialLibraries.count):
            m = app.materialLibraries.item(i).materials.itemByName(name)
            if m:
                return m
    return None


def set_property(design, mat, key, value, units, notes):
    """Set a physical property, converting from our units to whatever units Fusion stores it in."""
    props = mat.materialProperties
    for i in range(props.count):
        p = props.item(i)
        if key.lower() in p.name.lower() and hasattr(p, "value"):
            try:
                target = getattr(p, "units", "") or units
                p.value = design.unitsManager.convert(value, units, target)
                return
            except Exception:
                break
    notes.append(f"{mat.name}: set {key} = {value} {units} by hand (Manage Physical Materials)")


def make_materials(app, design, spec, notes):
    out = {}
    for key, m in spec.items():
        mat = design.materials.itemByName(m["name"]) or find_material(app, [m["name"]])
        if mat is None:
            base = find_material(app, m["base"])
            if base is None:
                notes.append(f"no library material for {m['name']} (tried {', '.join(m['base'])}): assign it by hand")
                out[key] = None
                continue
            if not m.get("props"):                 # plain library material
                out[key] = base
                continue
            mat = design.materials.addByCopy(base, m["name"])
            for prop, (value, units) in m["props"].items():
                set_property(design, mat, prop, value, units, notes)
        out[key] = mat
    return out


def all_bodies(root):
    for b in root.bRepBodies:
        yield b
    for occ in root.allOccurrences:
        for b in occ.bRepBodies:
            yield b


def run(context):
    app = adsk.core.Application.get()
    ui = app.userInterface
    try:
        with open(os.path.join(HERE, "bodies.json"), encoding="utf8") as fh:
            spec = json.load(fh)
        doc = app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
        design = adsk.fusion.Design.cast(app.activeProduct)
        root = design.rootComponent
        im = app.importManager
        if not im.importToTarget(im.createSTEPImportOptions(os.path.join(HERE, spec["step"])), root):
            ui.messageBox("STEP import failed")
            return
        notes = []
        mats = make_materials(app, design, spec["materials"], notes)
        done, unknown = set(), []
        bodies = list(all_bodies(root))

        def volume(b):
            bb = b.boundingBox
            return ((bb.maxPoint.x - bb.minPoint.x) * (bb.maxPoint.y - bb.minPoint.y)
                    * (bb.maxPoint.z - bb.minPoint.z))
        board = max(range(len(bodies)), key=lambda i: volume(bodies[i]))   # the main board is the biggest body
        sized = [e for e in spec["bodies"] if not e.get("largest")]
        for i, body in enumerate(bodies):
            bb = body.boundingBox
            d = sorted(abs(a - b) * 10.0 for a, b in ((bb.maxPoint.x, bb.minPoint.x),
                                                      (bb.maxPoint.y, bb.minPoint.y),
                                                      (bb.maxPoint.z, bb.minPoint.z)))   # cm -> mm
            if i == board:
                hit = next(e for e in spec["bodies"] if e.get("largest"))
            else:
                hit = next((e for e in sized if all(abs(x - y) < TOL_MM for x, y in zip(d, e["dims"]))), None)
            if hit is None:
                unknown.append(f"{body.name} {d[0]:.2f} x {d[1]:.2f} x {d[2]:.2f} mm")
                continue
            native = body.nativeObject or body
            native.name = hit["label"]
            if mats.get(hit["material"]):
                native.material = mats[hit["material"]]
            done.add(hit["label"])
        missing = [e["label"] for e in spec["bodies"] if e["label"] not in done]
        if missing:
            notes.append("not found in the import: " + ", ".join(missing))
        if unknown:
            notes.append("bodies left without a material: " + "; ".join(unknown))
        out = os.path.join(HERE, spec["f3d"])
        em = design.exportManager
        em.execute(em.createFusionArchiveExportOptions(out))
        ui.messageBox(f"Saved {out}\n\n{len(done)} body types named and given materials.\n\n"
                      "Next: Simulation workspace > New Simulation Study, then add the heat loads "
                      "shown in the body names (see FUSION_SIM.md)."
                      + ("\n\nCheck:\n- " + "\n- ".join(notes) if notes else ""))
    except Exception:
        ui.messageBox("TredderSim failed:\n" + traceback.format_exc())
