"""
Write a placeholder 3D model (VRML) of the 2.0" ST7789 display module that
plugs into J4, so the KiCad 3D viewer shows where the screen sits.

Geometry is approximate (typical 2.0in 240x320 module, ~60 x 36 mm).
Replace it with your module's real dimensions once you have it.
Coordinates are in mm in J4's footprint frame (origin = pin 1, z up from the
board surface). KiCad reads VRML in units of 0.1 inch (2.54 mm) but ignores
a parent Transform's scale for Box sizes, so box() converts every number
itself instead of using a scale node (checked against kicad-cli renders).
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "3d", "lcd_2in0_st7789_module.wrl")

SOCKET_H = 8.5      # PinSocket_1x08 body height
SPACER_H = 2.54     # male header plastic on the module
PCB_T = 1.6
PANEL_T = 2.4

# Module PCB in J4 footprint coords (KiCad 3D: +y is footprint -y)
X0, X1 = -2.5, 57.5          # board x 2 .. 62
Y0, Y1 = 4.0, -32.0          # board y 2 .. 38


def box(cx, cy, cz, sx, sy, sz, rgb, spec=0.2, shin=0.2):
    r, g, b = rgb
    cx, cy, cz, sx, sy, sz = (v / 2.54 for v in (cx, cy, cz, sx, sy, sz))
    return (f"Transform {{ translation {cx:.4f} {cy:.4f} {cz:.4f} children [ Shape {{\n"
            f"  appearance Appearance {{ material Material {{ diffuseColor {r} {g} {b} "
            f"specularColor {spec} {spec} {spec} shininess {shin} }} }}\n"
            f"  geometry Box {{ size {sx:.4f} {sy:.4f} {sz:.4f} }} }} ] }}\n")


def main():
    parts = []
    z_pcb = SOCKET_H + SPACER_H
    # male pin strip: plastic spacer + gold pins
    parts.append(box(0, -8.89, SOCKET_H + SPACER_H / 2, 2.5, 20.3, SPACER_H, (0.05, 0.05, 0.05)))
    for i in range(8):
        parts.append(box(0, -2.54 * i, z_pcb - 3.0, 0.64, 0.64, 6.0, (0.85, 0.7, 0.2), 0.6, 0.6))
    # module PCB
    cx, cy = (X0 + X1) / 2, (Y0 + Y1) / 2
    parts.append(box(cx, cy, z_pcb + PCB_T / 2, X1 - X0, Y0 - Y1, PCB_T, (0.1, 0.25, 0.6)))
    # LCD panel (metal frame + backlight), ~49.5 x 34 mm, pushed toward the far end from the pins
    pw, ph = 49.5, 34.0
    pcx = X1 - 2.0 - pw / 2
    parts.append(box(pcx, cy, z_pcb + PCB_T + PANEL_T / 2, pw, ph, PANEL_T, (0.8, 0.8, 0.82), 0.5, 0.4))
    # active area 40.8 x 30.6 mm (2.0in, 320x240 landscape), glossy black
    parts.append(box(pcx - 2.0, cy, z_pcb + PCB_T + PANEL_T + 0.05, 40.8, 30.6, 0.1, (0.02, 0.02, 0.05), 0.9, 0.9))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8") as fh:
        fh.write("#VRML V2.0 utf8\n# Placeholder 2.0in ST7789 module (generated by tools/gen_lcd_model.py)\n")
        fh.write("".join(parts))


if __name__ == "__main__":
    main()
