"""
Generate platform/rp2350/board_pins.h from hardware/tools/design.py, so the
firmware pin map can never disagree with the PCB.

    python firmware/tools/gen_board_pins.py
"""
import os
import re
import sys

FW = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(FW, "..", "hardware", "tools"))
import design as D  # noqa: E402

OUT = os.path.join(FW, "platform", "rp2350", "board_pins.h")

# net name -> (macro, comment). Every GPIO net on the Pico must be listed here.
NAMES = {
    "SD_MISO": ("PIN_SD_MISO", "SPI0 RX"), "SD_CS": ("PIN_SD_CS", "SPI0 CSn (driven as GPIO)"),
    "SD_SCK": ("PIN_SD_SCK", "SPI0 SCK"), "SD_MOSI": ("PIN_SD_MOSI", "SPI0 TX"),
    "SD_DET": ("PIN_SD_DET", "card detect, low = inserted (verify DM3AT switch polarity)"),
    "SD_PWR_N": ("PIN_SD_PWR_N", "low = SD card powered (Q3)"),
    "LCD_PWR_N": ("PIN_LCD_PWR_N", "low = display module powered (Q5); drive LCD pins LOW before power-off"),
    "GP4": ("PIN_SPARE_GP4", "test pad TP7"), "GP18": ("PIN_SPARE_GP18", "test pad TP8"),
    "CHG_STAT": ("PIN_CHG_STAT", "input, no pull: low = charging, high = done / no USB"),
    "SE_SDA": ("PIN_SE_SDA", "I2C0 SDA (4.7k pull-up)"), "SE_SCL": ("PIN_SE_SCL", "I2C0 SCL (4.7k pull-up)"),
    "SE_RST_N": ("PIN_SE_RST_N", "OPTIGA reset, active low: drive LOW before SE power-off"),
    "SE_PWR_N": ("PIN_SE_PWR_N", "low = secure element powered (Q2)"),
    "BTN_BACK": ("PIN_BTN_BACK", "active low, external pull-up + RC debounce"),
    "BTN_CONFIRM": ("PIN_BTN_CONFIRM", "active low, external pull-up + RC debounce"),
    "BTN_UP": ("PIN_BTN_UP", "active low, external pull-up + RC debounce"),
    "BTN_DOWN": ("PIN_BTN_DOWN", "active low, external pull-up + RC debounce"),
    "UART_TX": ("PIN_UART_TX", "UART0 TX debug console (disable in production)"),
    "UART_RX": ("PIN_UART_RX", "UART0 RX debug console (disable in production)"),
    "LCD_BL_N": ("PIN_LCD_BL_N", "low = backlight on (Q4), PWM capable"),
    "LCD_RST": ("PIN_LCD_RST", "ST7789 reset, active low"), "LCD_CS": ("PIN_LCD_CS", "ST7789 CS (GPIO)"),
    "LCD_DC": ("PIN_LCD_DC", "ST7789 data/command"),
    "LCD_SCK": ("PIN_LCD_SCK", "SPI1 SCK"), "LCD_MOSI": ("PIN_LCD_MOSI", "SPI1 TX"),
    "VBAT_SENSE": ("PIN_VBAT_ADC", "ADC2; VBAT = 2 x reading (calibrate per device)"),
}


def main():
    pin_net = D.check()
    gp_pin = {name: num for num, name in D.TYPES["PICO2W"]["left"] + D.TYPES["PICO2W"]["right"]
              if re.match(r"GP\d+", name)}
    rows, seen = [], set()
    for name, num in gp_pin.items():
        net = pin_net.get(f"A1.{num}")
        if not net:
            continue
        if net not in NAMES:
            sys.exit(f"net {net} on {name} has no firmware name: add it to NAMES")
        macro, comment = NAMES[net]
        rows.append((int(re.match(r"GP(\d+)", name).group(1)), macro, comment, net))
        seen.add(net)
    missing = set(NAMES) - seen
    if missing:
        sys.exit(f"NAMES lists nets not on any GPIO: {sorted(missing)}")
    rows.sort()
    r8 = D.P["R8"]["value"]
    L = ["/* GENERATED by firmware/tools/gen_board_pins.py from hardware/tools/design.py. Do not edit. */",
         "#ifndef BOARD_PINS_H", "#define BOARD_PINS_H", ""]
    w = max(len(m) for _, m, _, _ in rows)
    L += [f"#define {m:<{w}} {gp:>2}u  /* {cmt} [{net}] */" for gp, m, cmt, net in rows]
    L += ["",
          "#define BOARD_SD_SPI   spi0",
          "#define BOARD_LCD_SPI  spi1",
          "#define BOARD_SE_I2C   i2c0",
          "#define BOARD_DBG_UART uart0",
          "#define BOARD_VBAT_ADC_INPUT 2u",
          f"#define BOARD_VBAT_DIVIDER_NUM {int(D.P['R10']['value'].rstrip('k').replace('.', '')) + int(D.P['R11']['value'].rstrip('k').replace('.', ''))}u",
          f"#define BOARD_VBAT_DIVIDER_DEN {int(D.P['R11']['value'].rstrip('k').replace('.', ''))}u",
          f"/* charger STAT divider bottom resistor: R8 = {r8} */",
          "", "#endif", ""]
    with open(OUT, "w", encoding="utf8", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"wrote {OUT} ({len(rows)} pins)")


if __name__ == "__main__":
    main()
