"""
Independent implementation of the backup file format (core/include/wallet/backup.h) in Python,
used to generate tests/host/backup_vectors.h. The C code must produce these files byte for byte
and open them.

Built only from: argon2-cffi (the Argon2 reference implementation), `cryptography`
(ChaCha20-Poly1305 via OpenSSL) and hashlib. No code shared with the firmware.

    pip install argon2-cffi cryptography
    python firmware/tools/gen_backup_vectors.py
"""
import hashlib
import os
import random
import struct

from argon2.low_level import Type, hash_secret_raw
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

OUT = os.path.join(os.path.dirname(__file__), "..", "tests", "host", "backup_vectors.h")


def entropy_to_indices(ent: bytes) -> list:
    """BIP39: entropy + first len/32 bits of SHA-256 -> 11-bit word indices."""
    bits = len(ent) * 8
    cs = bits // 32
    n = int.from_bytes(ent, "big") << cs | hashlib.sha256(ent).digest()[0] >> (8 - cs)
    words = (bits + cs) // 11
    return [(n >> (11 * (words - 1 - i))) & 0x7FF for i in range(words)]


def seal(seed_idx, blind, pw_ent, demo, m_kib, passes, salt, nonce):
    hdr = b"TREDDERB" + bytes([1, 1 if demo else 0, 2, 1]) + struct.pack("<II", m_kib, passes) + salt + nonce + \
        struct.pack("<HH", 64, 0)
    assert len(hdr) == 52
    pt = bytes([1, len(seed_idx), 1 if blind else 0, 0]) + b"".join(struct.pack("<H", i) for i in seed_idx)
    pt = pt.ljust(64, b"\0")
    key = hash_secret_raw(pw_ent, salt, time_cost=passes, memory_cost=m_kib, parallelism=1, hash_len=32, type=Type.ID)
    ct_tag = ChaCha20Poly1305(key).encrypt(nonce, pt, hdr)
    body = hdr + ct_tag
    return body + hashlib.sha256(body).digest()[:8]


def carr(b):
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def main():
    rnd = random.Random(20261108)
    cases = []
    for (seed_len, blind, demo, m_kib, passes) in [
        (16, False, False, 64, 3), (32, True, False, 64, 3), (16, False, True, 8, 1), (24, True, True, 32, 2),
        (20, False, False, 16, 5), (28, False, True, 64, 1), (32, False, False, 8, 4), (16, True, False, 64, 8),
    ]:
        seed_idx = entropy_to_indices(rnd.randbytes(seed_len))
        pw_ent = rnd.randbytes(16)
        pw_idx = entropy_to_indices(pw_ent)
        salt, nonce = rnd.randbytes(16), rnd.randbytes(12)
        f = seal(seed_idx, blind, pw_ent, demo, m_kib, passes, salt, nonce)
        assert len(f) == 140
        cases.append((seed_idx, blind, pw_idx, demo, m_kib, passes, salt, nonce, f))

    # raw Argon2id outputs (pass, salt, m_kib, t) for the KDF alone
    raw = []
    for (m, t) in [(8, 1), (8, 3), (64, 3), (37, 2)]:
        p, s = rnd.randbytes(16), rnd.randbytes(16)
        raw.append((p, s, m, t, hash_secret_raw(p, s, t, m, 1, 32, Type.ID)))

    with open(OUT, "w", newline="\n") as o:
        o.write("/* GENERATED by tools/gen_backup_vectors.py (argon2-cffi + cryptography): do not edit. */\n")
        o.write("#include <stdbool.h>\n#include <stdint.h>\n\n")
        o.write("typedef struct {\n  uint8_t words; uint16_t idx[24]; bool blind; uint16_t pw[12]; bool demo;\n"
                "  uint32_t m_kib, passes; uint8_t salt[16], nonce[12], file[140];\n} backup_vec_t;\n\n")
        o.write("static const backup_vec_t BACKUP_VECTORS[] = {\n")
        for (seed_idx, blind, pw_idx, demo, m, t, salt, nonce, f) in cases:
            o.write(f"  {{{len(seed_idx)}, {{{', '.join(map(str, seed_idx))}}}, {str(blind).lower()},\n"
                    f"   {{{', '.join(map(str, pw_idx))}}}, {str(demo).lower()}, {m}, {t},\n"
                    f"   {carr(salt)},\n   {carr(nonce)},\n   {carr(f)}}},\n")
        o.write("};\n\n")
        o.write("typedef struct { uint8_t pass[16], salt[16]; uint32_t m_kib, passes; uint8_t out[32]; } argon2_vec_t;\n")
        o.write("static const argon2_vec_t ARGON2_VECTORS[] = {\n")
        for (p, s, m, t, h) in raw:
            o.write(f"  {{{carr(p)}, {carr(s)}, {m}, {t}, {carr(h)}}},\n")
        o.write("};\n")
    print(f"{len(cases)} backup files + {len(raw)} Argon2id vectors -> {os.path.abspath(OUT)}")


if __name__ == "__main__":
    main()
