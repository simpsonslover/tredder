"""
Generate the display fonts (firmware/app/src/font_data.c) from DejaVu fonts.

    python firmware/tools/gen_font.py

Glyphs are 4-bit anti-aliasing masks, two pixels per byte (high nibble first),
rows packed without padding. DejaVu fonts: Bitstream Vera licence (free to
embed and redistribute); the TTFs come from matplotlib's bundled copy.
"""
import os

import matplotlib
from PIL import Image, ImageDraw, ImageFont

FW = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TTF = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")
OUT = os.path.join(FW, "app", "src", "font_data.c")

EXTRA = "✓✗▲▼•…≈—←→⚠"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)

# Icons: Ionicons (MIT licence, the same set the phone app uses), as private-use code points
# U+E000.. in the order below, each glyph centred in a size x size box (top-left = draw position).
APP_NM = os.path.join(FW, "..", "app", "node_modules", "@expo", "vector-icons", "build", "vendor", "react-native-vector-icons")
ION_TTF = os.path.join(APP_NM, "Fonts", "Ionicons.ttf")
ION_MAP = os.path.join(APP_NM, "glyphmaps", "Ionicons.json")
ICONS = [
    "lock-closed", "lock-open", "add-circle-outline", "download-outline", "save-outline", "shield-checkmark",
    "trash-outline", "key-outline", "bluetooth", "eye-off-outline", "wallet-outline", "phone-portrait-outline",
    "checkmark-circle", "warning", "close-circle", "information-circle", "hourglass-outline", "refresh",
    "arrow-undo", "swap-horizontal", "document-text-outline", "alert-circle",
]
ICON_FONTS = [("wl_icons", 18), ("wl_icons_big", 48)]
# + one more glyph after ICONS: the tredder logo, from the app icon (white strokes on #373737)
LOGO_PNG = os.path.join(FW, "..", "app", "assets", "icon.png")

FONTS = [
    # C name, file, pixel size
    ("wl_font_body", "DejaVuSansMono.ttf", 15),
    ("wl_font_bold", "DejaVuSansMono-Bold.ttf", 15),
    ("wl_font_title", "DejaVuSans-Bold.ttf", 19),
    ("wl_font_big", "DejaVuSansMono-Bold.ttf", 30),
]


def render(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CHARS:
        if ch != " " and font.getmask(ch).getbbox() is None:
            raise SystemExit(f"{os.path.basename(path)} lacks {ch!r}")
        adv = round(font.getlength(ch))
        bbox = font.getbbox(ch)  # relative to the top of the ascent line
        x0, y0, x1, y1 = bbox if ch != " " else (0, 0, 0, 0)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = Image.new("L", (max(1, w), max(1, h)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        off = len(data)
        px = [img.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
        if len(px) % 2:
            px.append(0)
        for i in range(0, len(px), 2):
            data.append((px[i] << 4) | px[i + 1])
        glyphs.append((ord(ch), w, h, x0, y0, adv, off))
    return ascent + descent, ascent, glyphs, data


def render_icons(size):
    import json
    cmap = json.load(open(ION_MAP, encoding="utf-8"))
    font = ImageFont.truetype(ION_TTF, size)
    glyphs, data = [], bytearray()
    for i, name in enumerate(ICONS):
        ch = chr(cmap[name])
        img = Image.new("L", (size, size), 0)
        x0, y0, x1, y1 = font.getbbox(ch)
        ImageDraw.Draw(img).text(((size - (x1 - x0)) / 2 - x0, (size - (y1 - y0)) / 2 - y0), ch, font=font, fill=255)
        off = len(data)
        px = [img.getpixel((x, y)) >> 4 for y in range(size) for x in range(size)]
        if len(px) % 2:
            px.append(0)
        for k in range(0, len(px), 2):
            data.append((px[k] << 4) | px[k + 1])
        glyphs.append((0xE000 + i, size, size, 0, 0, size, off))
    logo = Image.open(LOGO_PNG).convert("L").resize((size, size), Image.LANCZOS)
    off = len(data)
    px = [max(0, min(255, (logo.getpixel((x, y)) - 55) * 255 // 200)) >> 4 for y in range(size) for x in range(size)]
    if len(px) % 2:
        px.append(0)
    for k in range(0, len(px), 2):
        data.append((px[k] << 4) | px[k + 1])
    glyphs.append((0xE000 + len(ICONS), size, size, 0, 0, size, off))
    return size, size, glyphs, data


def main():
    out = [
        "/* GENERATED by firmware/tools/gen_font.py from DejaVu fonts (Bitstream Vera licence) and Ionicons (MIT). Do not edit. */",
        '#include "app/gfx.h"',
        "",
    ]
    jobs = [(n, lambda f=f, z=z: render(os.path.join(TTF, f), z)) for n, f, z in FONTS] +         [(n, lambda z=z: render_icons(z)) for n, z in ICON_FONTS]
    for name, job in jobs:
        height, ascent, glyphs, data = job()
        out.append(f"static const uint8_t {name}_bits[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const wl_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for cp, w, h, x0, y0, adv, off in glyphs:
            out.append(f"  {{0x{cp:04x}, {w}, {h}, {x0}, {y0}, {adv}, {off}}},")
        out.append("};")
        out.append(f"const wl_font_t {name} = {{{height}, {ascent}, {len(glyphs)}, {name}_glyphs, {name}_bits}};")
        out.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
