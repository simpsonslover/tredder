/*
 * Export the PUBLIC data a device would return for the public BIP39 test phrase
 * "abandon x11 about", using the real wallet core. The app's mock device serves
 * this file, and the app's tests check their watch-only derivation against the
 * firmware-derived addresses listed here.
 *
 * Contains no private keys or seed. Built and run by:
 *   python firmware/tools/host_test.py --export-mock app/src/dev/mockDeviceData.json
 */
#include <stdio.h>
#include <string.h>

#include "wallet/address.h"
#include "wallet/mnemonic.h"
#include "wallet/schemes.h"
#include "wallet/secure.h"

static const char *const PHRASE =
    "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";

static void hex(FILE *f, const uint8_t *b, size_t n) {
  for (size_t i = 0; i < n; i++) fprintf(f, "%02x", b[i]);
}

int main(int argc, char **argv) {
  if (argc != 2) {
    fprintf(stderr, "usage: mock_export <out.json>\n");
    return 2;
  }
  uint16_t idx[24];
  size_t words, bad;
  uint8_t seed[64];
  if (wl_mnemonic_parse(PHRASE, idx, &words, &bad) != WL_OK || wl_mnemonic_to_seed(idx, words, "", seed) != WL_OK)
    return 1;
  FILE *f = fopen(argv[1], "w");
  if (!f) return 1;
  fprintf(f, "{\n  \"note\": \"PUBLIC test phrase 'abandon x11 about'. Generated by firmware/tools/mock_export.c. Never send funds here.\",\n");
  fprintf(f, "  \"accounts\": [\n");
  int first = 1;
  for (int net = 0; net <= 1; net++) {
    for (int s = 0; s < WL_SCHEME_COUNT; s++) {
      const wl_scheme_info_t *info = wl_scheme_info((wl_scheme_t)s);
      if (net == WL_NET_TEST && info->chain != WL_CHAIN_BTC) continue; /* EVM/SOL addresses are network-independent */
      uint32_t max = info->max_account == 0 ? 0 : (info->chain == WL_CHAIN_BTC ? 2 : 4);
      for (uint32_t a = 0; a <= max; a++) {
        uint32_t path[WL_MAX_PATH_DEPTH];
        size_t depth;
        char ps[64];
        wl_scheme_path((wl_scheme_t)s, (wl_net_t)net, a, 0, 0, path, &depth);
        if (info->chain == WL_CHAIN_BTC) depth = 3; /* account level */
        wl_path_to_string(path, depth, ps, sizeof(ps));
        if (s == WL_SCHEME_SOL_CLI_SEED) strcpy(ps, "seed[0:32]");
        fprintf(f, "%s    {\"net\": \"%s\", \"scheme\": \"%s\", \"account\": %lu, \"path\": \"%s\", ", first ? "" : ",\n",
                net ? "test" : "main", info->name, (unsigned long)a, ps);
        first = 0;
        if (info->chain == WL_CHAIN_BTC) {
          wl_account_key_t k;
          if (wl_account_key(seed, (wl_scheme_t)s, (wl_net_t)net, a, &k) != WL_OK) return 1;
          fprintf(f, "\"kind\": \"xpub\", \"publicKey\": \"");
          hex(f, k.public_key, 33);
          fprintf(f, "\", \"chainCode\": \"");
          hex(f, k.chain_code, 32);
          fprintf(f, "\", \"masterFingerprint\": %lu}", (unsigned long)k.master_fingerprint);
        } else {
          char addr[WL_ADDRESS_MAX_LEN];
          if (wl_address(seed, (wl_scheme_t)s, WL_NET_MAIN, a, 0, 0, addr, sizeof(addr)) != WL_OK) return 1;
          fprintf(f, "\"kind\": \"address\", \"address\": \"%s\"}", addr);
        }
      }
    }
  }
  fprintf(f, "\n  ],\n  \"btcAddresses\": [\n");
  first = 1;
  for (int net = 0; net <= 1; net++) {
    for (int s = WL_SCHEME_BTC_LEGACY; s <= WL_SCHEME_BTC_TAPROOT; s++) {
      for (uint32_t a = 0; a <= 1; a++) {
        static const uint32_t ci[][2] = {{0, 0}, {0, 1}, {0, 2}, {1, 0}, {1, 3}};
        for (size_t k = 0; k < sizeof(ci) / sizeof(ci[0]); k++) {
          char addr[WL_ADDRESS_MAX_LEN];
          if (wl_address(seed, (wl_scheme_t)s, (wl_net_t)net, a, ci[k][0], ci[k][1], addr, sizeof(addr)) != WL_OK)
            return 1;
          fprintf(f, "%s    {\"net\": \"%s\", \"scheme\": \"%s\", \"account\": %lu, \"change\": %lu, \"index\": %lu, \"address\": \"%s\"}",
                  first ? "" : ",\n", net ? "test" : "main", wl_scheme_info((wl_scheme_t)s)->name, (unsigned long)a,
                  (unsigned long)ci[k][0], (unsigned long)ci[k][1], addr);
          first = 0;
        }
      }
    }
  }
  fprintf(f, "\n  ]\n}\n");
  fclose(f);
  wl_wipe(seed, sizeof(seed));
  wl_wipe(idx, sizeof(idx));
  return 0;
}
