export type PriceSource = 'coinbase' | 'kraken' | 'pyth' | 'chainlink' | 'dexscreener';

export interface PriceQuote {
  usd: number;
  source: PriceSource;
}

const TTL_MS = 15_000; // fixed-list sources are read at most this often
const KEEP_MS = 10 * 60_000; // a source that stops answering: its last prices are used this long
const PYTH_MAX_AGE_S = 600;
const PYTH_MAX_CONF = 0.02; // Pyth's own uncertainty above 2% of the price: not used
const DEX_MIN_LIQUIDITY = 1_000;

