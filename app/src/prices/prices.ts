// USD prices, refreshed every 15 s (WalletContext) from:
//
//   Coinbase     big coins only (each chain's coin, stablecoins, WBTC, LINK, UNI, AAVE). One request.
//   Kraken       the main server for every other listed token. One request, a fixed list of pairs.
//   Pyth         the price accounts Pyth keeps fresh on Solana (SOL, stablecoins, JUP, JTO, PYTH,
//                staked SOL...), read through the app's Solana server: no extra website.
//   Chainlink    big coins, last resort: only read when Coinbase and Kraken both fail (Ethereum
//                feeds, through the app's Ethereum server).
//   DexScreener  meme coins none of the above has.
//
// Privacy: Coinbase, Kraken, Pyth and Chainlink are always asked for the same fixed list, whatever
// the wallet holds; they learn nothing about its coins. DexScreener is asked for the exact tokens
// held that nothing else prices, so it can see those.
//
// Safety: a token is priced by an exchange only if its CONTRACT ADDRESS is in priceTable.ts
// (generated by scripts/price-table.mts, each source checked against the price of that exact
// address). Never by name: anyone can deploy a token called "USDC", and exchange tickers collide.
