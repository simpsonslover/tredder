const tokenKey = (h: Pick<Holding, 'chain' | 'asset'>) =>
  h.asset.kind === 'native' ? '' : `${h.chain}:${h.chain === 'sol' ? h.asset.address : h.asset.address.toLowerCase()}`;

/** The route and the order its sources are tried in, or undefined (DexScreener's turn). */
function routeOf(h: Holding): { r: Route; order: Src[] } | undefined {
  if (h.asset.kind === 'native') return { r: NATIVE_ROUTE[h.chain], order: ['cb', 'kr', 'py', 'cl'] };
  const k = tokenKey(h);
  const t = TOKEN_ROUTES[k];
  const cl = CHAINLINK_TOKEN[k];
  if (!t && !cl) return undefined;
  const r: Route = { s: t?.s ?? cl!, ...t, cl };
  if (BIG.has(r.s) || cl) return { r, order: ['cb', 'kr', 'py', 'cl'] };
  // Coinbase is for big coins only
  if (h.chain === 'sol' && r.py) return { r, order: ['py', 'kr'] };
  return { r, order: ['kr', 'py'] };
}

/* ---------- reading the sources ---------- */

/** Coinbase: every USD rate in one request (symbol -> USD). */
export async function readCoinbase(): Promise<Record<string, number>> {
  const r = await getJson<{ data: { rates: Record<string, string> } }>('https://api.coinbase.com/v2/exchange-rates?currency=USD');
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(r.data.rates)) if (Number(v) > 0) out[k] = 1 / Number(v);
  return out;
}

/** Kraken: last trade price of every pair in priceTable.ts, one request (pair -> USD). */
export async function readKraken(): Promise<Record<string, number>> {
  const r = await getJson<{ error: string[]; result?: Record<string, { c: [string] }> }>(`https://api.kraken.com/0/public/Ticker?pair=${KRAKEN_PAIRS.join(',')}`);
  if (r.error?.length) throw new Error(`Kraken: ${r.error.join(', ')}`);
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(r.result ?? {})) if (Number(v.c[0]) > 0) out[k] = Number(v.c[0]);
  return out;
}

const PYTH_PROGRAM = new PublicKey('pythWSnswVUd12oZpeFP8e9CVaEqJg25g1Vtc2biRsT'); // Pyth push oracle (shard 0)
let pythAccounts: { sym: string; id: string; pda: PublicKey }[] | null = null;

// Little-endian reads on plain bytes (no Buffer methods: same result in Node and on the phone).
const u64 = (b: Uint8Array, o: number) => {
  let v = 0n;
  for (let i = 7; i >= 0; i--) v = (v << 8n) | BigInt(b[o + i]!);
  return v;
};
const i64 = (b: Uint8Array, o: number) => {
  const v = u64(b, o);
  return v >= 1n << 63n ? v - (1n << 64n) : v;
};
const i32 = (b: Uint8Array, o: number) => b[o]! | (b[o + 1]! << 8) | (b[o + 2]! << 16) | (b[o + 3]! << 24);
const hexOf = (b: Uint8Array) => Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
const bytesOf = (hex: string) => Uint8Array.from(hex.match(/../g) ?? [], (x) => parseInt(x, 16));

/** Pyth price account (PriceUpdateV2) -> USD, or undefined if it is not that feed, old, or unsure. */
export function decodePythAccount(b: Uint8Array, feedId: string, nowS = Date.now() / 1000): number | undefined {
  let o = 8 + 32; // discriminator, write authority
  if (b.length < o + 2) return undefined;
  o += b[o] === 0 ? 2 : 1; // verification level: Partial { num_signatures } | Full
  if (b.length < o + 32 + 8 + 8 + 4 + 8) return undefined;
  if (hexOf(b.subarray(o, o + 32)) !== feedId) return undefined;
  const raw = i64(b, o + 32);
  const conf = u64(b, o + 40);
  const expo = i32(b, o + 48);
  const publishTime = Number(i64(b, o + 52));
  if (raw <= 0n || nowS - publishTime > PYTH_MAX_AGE_S || Number(conf) / Number(raw) > PYTH_MAX_CONF) return undefined;
  return Number(raw) * 10 ** expo;
}

/** Pyth: the feeds Pyth keeps fresh on Solana, one request to the app's Solana server (symbol -> USD). */
export async function readPyth(): Promise<Record<string, number>> {
  pythAccounts ??= Object.entries(PYTH_SOLANA).map(([sym, id]) => ({
    sym,
    id,
    pda: PublicKey.findProgramAddressSync([new Uint8Array([0, 0]), bytesOf(id)], PYTH_PROGRAM)[0],
  }));
  const accs = await solConnection('main').getMultipleAccountsInfo(pythAccounts.map((a) => a.pda));
  const out: Record<string, number> = {};
  accs.forEach((a, i) => {
    const f = pythAccounts![i]!;
    const usd = a ? decodePythAccount(a.data, f.id) : undefined;
    if (usd !== undefined) out[f.sym] = usd;
  });
  return out;
}

const CL_ABI = parseAbi(['function latestRoundData() view returns (uint80, int256, uint256, uint256, uint80)']);
const CL_IDS = Object.keys(CHAINLINK) as ClId[];
const MULTICALL3: Address = '0xcA11bde05977b3631167028862bE2a173976CA11'; // same address on every EVM chain

/** Chainlink: every feed in one request through the app's Ethereum server. Stale (> 48 h) or zero feeds are left out. */
export async function readChainlink(): Promise<ChainlinkValues> {
  const res = await evmClient('eth', 'main').multicall({
    allowFailure: true,
    multicallAddress: MULTICALL3,
    contracts: CL_IDS.map((id) => ({ address: CHAINLINK[id], abi: CL_ABI, functionName: 'latestRoundData' }) as const),
  });
  const now = Date.now() / 1000;
  const out: ChainlinkValues = {};
  res.forEach((r, i) => {
    if (r.status !== 'success') return;
    const [, answer, , updatedAt] = r.result as readonly [bigint, bigint, bigint, bigint, bigint];
    if (answer <= 0n || now - Number(updatedAt) > 48 * 3600) return;
    out[CL_IDS[i]!] = Number(answer) / 1e8;
  });
  return out;
}

const DEX_CHAIN: Record<ChainId, string | undefined> = { btc: undefined, eth: 'ethereum', base: 'base', bnb: 'bsc', polygon: 'polygon', arbitrum: 'arbitrum', sol: 'solana' };

/** DexScreener: the most liquid pair's USD price for these tokens of one chain (address -> USD). */
export async function readDexScreener(chain: ChainId, addresses: string[]): Promise<Record<string, number>> {
  const dexChain = DEX_CHAIN[chain];
  const out: Record<string, number> = {};
  if (!dexChain) return out;
  for (let i = 0; i < addresses.length; i += 30) {
    const chunk = addresses.slice(i, i + 30);
    const pairs = await getJson<{ baseToken: { address: string }; priceUsd?: string; liquidity?: { usd?: number } }[]>(
      `https://api.dexscreener.com/tokens/v1/${dexChain}/${chunk.join(',')}`,
    );
    for (const a of chunk) {
      const best = pairs
        .filter((p) => p.baseToken.address.toLowerCase() === a.toLowerCase() && p.priceUsd)
        .sort((x, y) => (y.liquidity?.usd ?? 0) - (x.liquidity?.usd ?? 0))[0];
      if (best && (best.liquidity?.usd ?? 0) >= DEX_MIN_LIQUIDITY) out[a] = Number(best.priceUsd);
    }
  }
  return out;
}

export interface Sources {
  coinbase: () => Promise<Record<string, number>>;
  kraken: () => Promise<Record<string, number>>;
  pyth: () => Promise<Record<string, number>>;
  chainlink: () => Promise<ChainlinkValues>;
  dexscreener: (chain: ChainId, addresses: string[]) => Promise<Record<string, number>>;
}
const SOURCES: Sources = { coinbase: readCoinbase, kraken: readKraken, pyth: readPyth, chainlink: readChainlink, dexscreener: readDexScreener };

/* ---------- state: last answer of each source ---------- */

type Got<T> = { at: number; v: T } | null;
let cb: Got<Record<string, number>> = null;
let kr: Got<Record<string, number>> = null;
let py: Got<Record<string, number>> = null;
let cl: Got<ChainlinkValues> = null;
const dex = new Map<string, { at: number; usd: number | null }>(); // tokenKey -> price (null: none found)
let lastRead = 0;
let inflight: Promise<void> | null = null;

const fresh = <T,>(g: Got<T>, now: number) => (g && now - g.at < KEEP_MS ? g.v : undefined);

async function readFixed(src: Sources): Promise<void> {
  const [a, b, c] = await Promise.allSettled([src.coinbase(), src.kraken(), src.pyth()]);
  const now = Date.now();
  if (a.status === 'fulfilled') cb = { at: now, v: a.value };
  if (b.status === 'fulfilled') kr = { at: now, v: b.value };
  if (c.status === 'fulfilled') py = { at: now, v: c.value };
  // Chainlink only when neither exchange answers
  if (!fresh(cb, now) && !fresh(kr, now)) {
    try {
      cl = { at: now, v: await src.chainlink() };
    } catch {
      /* keep whatever there is */
    }
  }
  lastRead = now;
}

function valueFrom(s: Src, r: Route, now: number): number | undefined {
  if (s === 'cb') return r.cb ? fresh(cb, now)?.[r.cb] : undefined;
  if (s === 'kr') return r.kr ? fresh(kr, now)?.[r.kr] : undefined;
  if (s === 'py') return r.py ? fresh(py, now)?.[r.py] : undefined;
  const v = fresh(cl, now);
  if (!r.cl || !v) return undefined;
  if (r.cl === 'WBTC_BTC') return v.BTC !== undefined && v.WBTC_BTC !== undefined ? v.BTC * v.WBTC_BTC : undefined;
  return v[r.cl];
}
const SOURCE_NAME: Record<Src, PriceSource> = { cb: 'coinbase', kr: 'kraken', py: 'pyth', cl: 'chainlink' };

const priceable = (h: Holding) => h.net === 'main' && (h.kind === 'native' || h.kind === 'token' || h.kind === 'staked');

/** Price of one holding from what has been read so far (no network). */
export function quoteOf(h: Holding, now = Date.now()): PriceQuote | undefined {
  if (!priceable(h)) return undefined;
  const route = routeOf(h);
  if (route) {
    for (const s of route.order) {
      const usd = valueFrom(s, route.r, now);
      if (usd !== undefined && Number.isFinite(usd) && usd > 0) return { usd, source: SOURCE_NAME[s] };
    }
    return undefined;
  }
  const d = dex.get(tokenKey(h));
  return d && d.usd !== null && now - d.at < KEEP_MS ? { usd: d.usd, source: 'dexscreener' } : undefined;
}

function quotes(holdings: Holding[]): Map<string, PriceQuote> {
  const out = new Map<string, PriceQuote>();
  const now = Date.now();
  for (const h of holdings) {
    const q = quoteOf(h, now);
    if (q) out.set(assetKey(h), q);
  }
  return out;
}

/** Prices for these holdings. The fixed-list sources are read at most every 15 s; DexScreener
 *  only for held tokens nothing else prices. A source that fails keeps its last prices for 10 min. */
export async function priceHoldings(holdings: Holding[], src: Sources = SOURCES): Promise<Map<string, PriceQuote>> {
  const live = holdings.filter(priceable);
  if (!live.length) return new Map(); // testnet: nothing to price, no request
  if (Date.now() - lastRead >= TTL_MS) {
    inflight ??= readFixed(src).finally(() => (inflight = null));
    await inflight;
  }
  // meme coins: tokens with no route, not looked up in the last 15 s
  const now = Date.now();
  const byChain = new Map<ChainId, string[]>();
  for (const h of live) {
    if (h.asset.kind !== 'token' || routeOf(h)) continue;
    const d = dex.get(tokenKey(h));
    if (d && now - d.at < TTL_MS) continue;
    const list = byChain.get(h.chain) ?? [];
    if (!list.includes(h.asset.address)) byChain.set(h.chain, [...list, h.asset.address]);
  }
  await Promise.all(
    [...byChain].map(async ([chain, addrs]) => {
      try {
        const got = await src.dexscreener(chain, addrs);
        const at = Date.now();
        for (const a of addrs) {
          const k = `${chain}:${chain === 'sol' ? a : a.toLowerCase()}`;
          const usd = got[a];
          if (usd !== undefined && Number.isFinite(usd) && usd > 0) dex.set(k, { at, usd });
          else if (!dex.get(k) || dex.get(k)!.usd === null) dex.set(k, { at, usd: null });
        }
      } catch {
        /* keep the last prices */
      }
    }),
  );
  return quotes(live);
}

/** Prices already read (no network): for partial totals while balances are still loading. */
export function cachedPrices(holdings: Holding[]): Map<string, PriceQuote> {
  return quotes(holdings.filter(priceable));
}

export function applyPrices(holdings: Holding[], prices: Map<string, PriceQuote>): Holding[] {
  return holdings.map((h) => {
    const q = h.net === 'main' ? prices.get(assetKey(h)) : undefined; // the key has no network: never price a testnet coin
    if (!q) return h;
    const usdValue = (Number(h.amount) / 10 ** h.decimals) * q.usd;
    return { ...h, usdPrice: q.usd, usdValue };
  });
}

export function clearPriceCache() {
  cb = kr = py = cl = null;
  dex.clear();
  lastRead = 0;
  inflight = null;
}
